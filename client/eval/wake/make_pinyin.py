"""Write thinksmart_client/pinyin.txt and kws_pinyin.txt from the 6763 GB2312 characters.

pinyin.txt: toneless pinyin, one syllable per line. wake_verify.py compares recognised text with the
wake words by sound, without shipping pypinyin (its phrase dictionary costs tens of MB of memory on
the device).
kws_pinyin.txt: every reading of each character as wake word model tokens (initial, final with tone:
the split sherpa-onnx's text2token makes, 小 = x iǎo, 一 = y ī, 阿 = ā), most common first; readings
with a token the model doesn't have are left out. wake_words.py turns a new wake word into keywords
with it.

    uv run --no-project --with pypinyin python eval/wake/make_pinyin.py
"""
import collections
import pathlib
import sys

from pypinyin import Style, lazy_pinyin, pinyin
from pypinyin.contrib.tone_convert import to_finals_tone, to_initials

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from common import CLIENT  # noqa: E402

MODEL_TOKENS = {line.split()[0] for line in (CLIENT / 'models' / 'kws-zh' / 'tokens.txt').read_text().splitlines() if line}


def kws_readings(ch):
    out = []
    for full in pinyin(ch, style=Style.TONE, heteronym=True)[0]:   # e.g. 哈: hā, há, hǎ, hà
        tokens = [t for t in (to_initials(full, strict=False), to_finals_tone(full, strict=False)) if t]
        if tokens and all(t in MODEL_TOKENS for t in tokens) and ' '.join(tokens) not in out:
            out.append(' '.join(tokens))
    return out


by_syllable = collections.defaultdict(list)
kws_lines = []
for hi in range(0xB0, 0xF8):
    for lo in range(0xA1, 0xFF):
        try:
            ch = bytes([hi, lo]).decode('gb2312')
        except UnicodeDecodeError:
            continue
        py = lazy_pinyin(ch, style=Style.NORMAL, errors='ignore')
        if py and py[0].isascii():
            by_syllable[py[0].replace('ü', 'v')].append(ch)
        readings = kws_readings(ch)
        if readings:
            kws_lines.append(f'{ch}\t{"|".join(readings)}')
lines = [f'{s}\t{"".join(chs)}' for s, chs in sorted(by_syllable.items())]
out = CLIENT / 'thinksmart_client' / 'pinyin.txt'
out.write_text('# generated by eval/wake/make_pinyin.py (pypinyin, GB2312 characters, most common reading)\n'
               + '\n'.join(lines) + '\n')
print(sum(len(c) for c in by_syllable.values()), 'characters,', len(lines), 'syllables ->', out)
kws_out = CLIENT / 'thinksmart_client' / 'kws_pinyin.txt'
kws_out.write_text('# generated by eval/wake/make_pinyin.py (pypinyin, GB2312 characters): character, readings as\n'
                   '# wake word model tokens separated by |, most common first\n' + '\n'.join(kws_lines) + '\n')
print(len(kws_lines), 'characters with', sum(line.count('|') + 1 for line in kws_lines), 'readings ->', kws_out)
